-- MuseAI 平台库 0036（R1 补齐项）：**运行时开关体系**。
--
-- `docs/VALIDATION.md` §0.1 原文写着运行时开关体系「列入 R1 开发」，但它既不在总规格 §19 的
-- R1 清单里，也不在台账初版中——两边都漏了（§3.1 已补记）。本迁移是补齐的数据侧那一层。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 为什么非做不可：验证计划本身依赖它
-- ═══════════════════════════════════════════════════════════════════════════
-- 现有 9 个开关全部是 **env 进程级**（`MUSE_ONBOARDING` / `MUSE_SUBPLOT_CARDS` /
-- `MUSE_LETHALITY_DEATHMATCH` / `MUSE_ROOM_INVITATIONS` / `MUSE_SAFETY_LEXICON` /
-- `MUSE_CONTAINER_ASSEMBLY` / `MUSE_MEMORIAL` / `MUSE_WORLD_SERIES_AUTOSCALE` /
-- `MUSE_WORLD_BE_BIOGRAPHY`），只有**全开/全关两态**：不能按世界灰度、不能按用户灰度、
-- 改一次要重启进程、运营在后台点不了。
--
-- 而 VALIDATION §2 的每个阶段都要求「开放范围」可控——T0「邀请制 ≤100 人」、T2「3-6 人世界」、
-- T3「订阅制灰度」。两态开关做不到分阶段开闸，于是**整个 T0-T5 验证计划悬空**。
-- 本表把「开放范围」变成可写的数据。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 本表**不改变任何现有模块的行为**（这是本批次最重要的约束）
-- ═══════════════════════════════════════════════════════════════════════════
-- 读取入口 `flags::is_enabled` 的回落链是：
--     按用户记录 → 按世界记录 → 全局记录 → **env（现有语义）** → 代码内声明的默认值
-- 本表**为空**时（迁移后的初始状态即为空）解析必然落到 env 分支，所以全部现存模块
-- 逐字节维持原行为。表里没有一行 = 什么都没变。开闸是**显式写入**，不是升级的副作用。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 默认关闭仍然是默认（VALIDATION §0.1，本批次最大风险点）
-- ═══════════════════════════════════════════════════════════════════════════
-- 引入一套开关体系最容易犯的错，是让「有了开关表」本身变成「功能被打开」。
-- 三道锁死：
--   ① 本迁移**不 INSERT 任何一行**（没有种子数据、没有默认全局记录）；
--   ② `enabled` 列 `DEFAULT 0`——即便将来有人写了半行记录，缺省也是关；
--   ③ 代码侧 `flags::KNOWN_FLAGS` 逐个声明默认值，有红线用例断言除审核链
--      （`MUSE_SAFETY_LEXICON`，关掉它等于放行敏感词，「安全」的方向是**开**）之外
--      全部默认为 false。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 fail-closed：任何异常都按「安全值」处理，绝不按开启处理
-- ═══════════════════════════════════════════════════════════════════════════
-- 查库失败 / scope 非法 / enabled 非 0-1 / 时间窗反转，一律**立即返回该开关声明的默认值**
-- 并且**不再继续回落到 env**（损坏的记录不该被静默跳过——跳过就等于「配坏了反而按 env 开着」）。
-- 对 8 个未验证功能，默认值 = false = 关；对审核链，默认值 = true = 继续过滤。
-- 「安全」永远指向不扩大用户可见范围的那一侧。
--
-- 双库可移植子集（`db.rs` 约定）：TEXT id / BIGINT 毫秒 / INTEGER 布尔 / 无方言特性
-- （无 JSONB、无 serial、无 NOW()、无 CHECK、无 ON CONFLICT、无 partial index、
--  无 strftime/date_trunc）。本迁移只新建一张表 + 索引，不改任何既有表结构（零回填、零锁表）。
-- 范式见 0031 / 0035。

CREATE TABLE runtime_flags (
  id TEXT PRIMARY KEY,

  -- 开关名。**与 env 变量名同名**（如 `MUSE_ONBOARDING`），不另造一套命名空间。
  -- 同名是刻意的：运营在后台看到的名字、工程在 `.env` 里写的名字、报警里出现的名字是同一个，
  -- 排查「那天为什么突然开放了」时不需要在两张词表之间做翻译。
  -- 合法取值由代码内 `flags::KNOWN_FLAGS` 白名单校验（写入端点拒绝未登记的开关名）——
  -- 不做数据库 CHECK 约束（方言不可移植），且白名单本就该随代码走。
  flag TEXT NOT NULL,

  -- 作用域：'global' | 'world' | 'user'。解析优先级 **user > world > global**（窄的赢）。
  -- 窄的赢是唯一合理的方向：运营给某个世界开了灰度之后，还要能对其中一个捣乱的用户单独关掉；
  -- 反过来（宽的赢）会让细粒度记录永远无效，那这套体系就退化回了两态开关。
  scope TEXT NOT NULL,

  -- 作用域目标 id。'global' 恒为空串（不是 NULL——空串参与唯一索引，NULL 在两种库里
  -- 对唯一索引的语义不同，见下方唯一索引注释）；'world' → `worlds.id`；'user' → `users.id`。
  --
  -- 🔴 **不建外键**，与 `prompt_versions.canary_world_ids` 的既有灰度先例同口径：
  -- 灰度名单是运营意图的记录，不是引用完整性的一部分。世界被删/用户被删之后残留一条记录，
  -- 后果只是「一条永不命中的记录」，而外键级联删除反而会**静默改变开放范围**（删个测试世界
  -- 顺手把灰度配置删了，事后无从复盘）。残留行由运营在列表页自行清理。
  target_id TEXT NOT NULL DEFAULT '',

  -- 开/关。INTEGER 0/1（双库可移植布尔）。DEFAULT 0 = 默认关闭的第二道锁。
  enabled INTEGER NOT NULL DEFAULT 0,

  -- ── 生效时间窗（可选，毫秒时间戳） ──────────────────────────────────────
  -- 0 表示不限。`starts_at=0 AND ends_at=0` 即「立即生效、永不过期」（最常见的用法）。
  --
  -- 窗口的产品用途是 VALIDATION §2 的**预注册纪律**：「开测前可修订、开测后冻结」。
  -- 把一批灰度写成 [T, T+14d] 的窗口，等于把「这轮测试跑两周」这件事写进数据，
  -- 而不是依赖某个人两周后记得回来关掉它。
  --
  -- 🔴 **窗口外 = 这条记录不参与解析**（回落到更宽的作用域），不是「窗口外强制关闭」。
  -- 两种语义都自洽，选前者是因为它可组合：给 100 个内测用户配 user 窗口期间他们看得到，
  -- 窗口一过他们自动跟随 world/global/env 的大盘状态，不需要再写一批「关闭」记录去覆盖。
  -- 若确实要「窗口内强制关闭」，写一条 `enabled=0` 且带窗口的记录即可——那是显式的，
  -- 与「窗口过期」区分得开。
  starts_at BIGINT NOT NULL DEFAULT 0,
  ends_at BIGINT NOT NULL DEFAULT 0,

  -- ── 审计留痕（红线：开关直接决定用户能看到什么，没有留痕就无法复盘） ──────
  -- 这三列与 `audit_logs` 是**互补而非重复**的：
  --   `audit_logs` 是**流水**（谁在何时做了哪些动作，只增不改，可回放全过程）；
  --   这三列是**现状**（这一行现在是谁留下的），使运营在列表页一眼看到责任人，
  --   不必为了回答「这条谁配的」去翻审计流水。两边都写，缺一不可。
  updated_by TEXT NOT NULL DEFAULT '',
  updated_at BIGINT NOT NULL,
  -- 变更理由。写入端点**强制非空**（`flags` 的写操作没有「不填理由」这个选项）——
  -- 理由是 §4.3 的纪律：开放范围的每一次变化都要能在事后说清「为什么」。
  reason TEXT NOT NULL DEFAULT '',

  created_at BIGINT NOT NULL
);

-- 🔴 唯一键 = (开关, 作用域, 目标)。**一个目标对一个开关至多一条记录**。
-- 允许多条会立刻制造「同一个用户对同一个开关既有开又有关」的不可判定局面，
-- 那时无论按 updated_at 取最新还是按 enabled 取保守，都是在用规则掩盖数据错误。
-- 唯一约束把它挡在写入处：设置 = upsert（先 UPDATE，无命中再 INSERT），语义是「覆盖」。
-- target_id 用空串而非 NULL 正是为了让 global 记录也落进这个唯一索引
-- （SQLite 与 Postgres 对「NULL 参与唯一索引」的判定不同，空串两边一致）。
CREATE UNIQUE INDEX idx_runtime_flags_key ON runtime_flags(flag, scope, target_id);

-- 读路径索引：解析时按 flag 取该开关的全部记录（当前实现走整表快照缓存，
-- 但缓存冷启动与 `MUSE_FLAGS_CACHE_TTL_MS=0`（禁用缓存）时是按 flag 查的，
-- 且运营列表页也按 flag 过滤）。最左前缀即 flag，无需再建单列索引。
CREATE INDEX idx_runtime_flags_flag_scope ON runtime_flags(flag, scope);
