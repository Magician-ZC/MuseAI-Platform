-- MuseAI 平台库 0043：**世界事件发号器** —— 修 `world_events.sequence` 的并发撞号。
-- 问题登记见 `docs/VALIDATION.md` §3.3 剩余项 ①。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 撞号的真正代价不是「显示顺序乱了」，是**断线补偿会永久漏推一条事件**
-- ═══════════════════════════════════════════════════════════════════════════
-- 分配口径原为事务内读-改-写：`SELECT COALESCE(MAX(sequence),-1)+1 FROM world_events WHERE world_id=?`，
-- 而 `idx_world_events_world(world_id, sequence)`（0001_init.sql:167）**非唯一**。
-- SQLite 的单写者锁让它事实上串行，**Postgres 在 READ COMMITTED 下不会**：
-- `SELECT MAX()` 不取任何锁，两个并发事务读到同一个 MAX 就各写一条同号事件，且**静默提交**。
--
-- 竞态真实可达（不是理论）：`arena/mod.rs:85` 的赛事系统事件是玩家/运营触发的 HTTP 路径，
-- 与 `runtime::commit_tick` 的批量落库并行，二者写的是同一个世界。
--
-- 爆炸半径里最重的一处是 `events/mod.rs` 的 `VISIBLE_EVENTS_SQL`——
-- 它拿 `sequence > $cursor` 当 **WS 断线补偿游标**。两条事件同号时，客户端收到前一条后把游标
-- 推到该值，后一条就**永远不会补给重连的客户端**：不是顺序抖动，是数据丢失。
-- 其余依赖 sequence 唯一性的站点：`clips/mod.rs` 的「后来者胜」高光规则、
-- `arena/mod.rs` 的回放 seek 分页、`slo/mod.rs` 的戏份聚合。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 为什么是发号器表，而不是给 `(world_id, sequence)` 加唯一索引
-- ═══════════════════════════════════════════════════════════════════════════
-- 唯一索引只是把「静默损坏」换成「23505 报错」，而报错的输家是**一整个 tick 的 commit 事务回滚**
-- ——即模型已经跑完、token 已经烧掉、世界状态 CAS 已经算好，全部作废重来。
-- 且唯一索引的迁移在存量已有重复行时会**直接失败 = 服务起不来**。
--
-- 本表让并发**根本不产生**冲突：分配在同一事务内三步走
--   ① `INSERT ... ON CONFLICT(world_id) DO NOTHING`（幂等建行）
--   ② `UPDATE world_event_seq SET next_seq = next_seq + n WHERE world_id = ?`
--   ③ `SELECT next_seq`（回读，区间为 `[next_seq - n, next_seq)`）
-- 正确性来自 ② 的**行级排他锁**：并发事务对同一行的 UPDATE 会阻塞到前者提交/回滚，
-- 再在**更新后**的值上叠加，不存在丢失更新。这是两个库都有的语义，
-- 不需要 `SELECT ... FOR UPDATE`（PG 方言）也不需要 `RETURNING`（SQLite 3.35+ 才有）。
--
-- 副作用是同一世界的事件写入被串行化——语义上本就该串行（sequence 是世界内的因果序）。
-- 锁窗很短：`commit_tick` 的事务在**模型调用之后**才开启，整段是纯 DB 语句、无任何外部 IO；
-- 分配点又排在该事务的尾部（投影 → 安全闸 → 落库），持锁到 commit 之间只剩两条小 UPDATE。
--
-- 事务回滚时 ② 的自增一并回滚，故本方案**不产生空洞**（与 PG 原生 sequence 不同）。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 回填：不回填 = 新号从 0 开始，与历史事件**逐条撞号**
-- ═══════════════════════════════════════════════════════════════════════════
-- 建完表必须把每个世界现有的 `MAX(sequence)+1` 灌进 `next_seq`，否则升级后的第一条事件
-- 就会拿到 0，把整段历史重新撞一遍——比原 bug 还严重。回填即下方第二条语句。
--
-- 迁移执行时刻与服务开始接客之间**没有窗口**：`db::connect()` 先 `migrate!().run(&pool)`
-- 跑完全部迁移，之后 `main` 才 bind 端口，同进程内不存在「迁移完了但旧口径还在写」的空隙。
-- 唯一残余窗口是**多实例滚动发布**（新实例跑完迁移开始接客时，旧实例仍在用 MAX+1 口径写）。
-- 对此的兜底在代码侧而非迁移侧：`events::allocate_sequences_tx` 的 ① 步建行时，初值取
-- `COALESCE((SELECT MAX(sequence)+1 FROM world_events WHERE world_id = ?), 0)` 而不是常数 0,
-- 于是任何**尚未登记进发号器**的世界（含本迁移之后才由旧口径写入首条事件的世界）在首次分配时
-- 自动对齐到既有历史之后。滚动发布中「旧实例往已登记世界继续写」这一种仍会撞号，
-- 处置是发布纪律（先停旧实例再放新实例），不是本迁移能解决的——如实记在这里。
--
-- 双库可移植子集（`db.rs` 约定）：TEXT id / BIGINT / 纯新建不 ALTER；
-- 无 JSONB、无 serial、无 NOW()、无 strftime/date_trunc、无 partial index。

-- ---------------------------------------------------------------------------
-- ① 发号器：每个世界一行
-- ---------------------------------------------------------------------------
CREATE TABLE world_event_seq (
  -- `worlds.id`。**不建外键**：世界删除与否不该牵动发号器的生命周期，
  -- 且发号器必须能给「尚未登记在 worlds 表」的 id 发号（口径同 0042 的 live_withholds）。
  -- PRIMARY KEY 同时就是并发分配所依赖的那把行锁的定位键。
  world_id TEXT PRIMARY KEY,

  -- 🔴 **下一个待发的号**（不是「已发的最大号」）。空世界为 0，即首条事件拿 0，
  -- 与改造前 `COALESCE(MAX(sequence), -1) + 1` 对空世界给出的 0 逐值一致。
  next_seq BIGINT NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------------------
-- ② 存量回填：每个已有事件的世界，从它现有的 MAX(sequence)+1 续上
-- ---------------------------------------------------------------------------
-- `sequence` 是 NOT NULL 列，故组内 MAX 恒非空，无需 COALESCE。
-- 没有事件的世界**故意不建行**：留给运行时首次分配按 DEFAULT 0 建，少一份要维护的口径。
INSERT INTO world_event_seq (world_id, next_seq)
SELECT world_id, MAX(sequence) + 1 FROM world_events GROUP BY world_id;
