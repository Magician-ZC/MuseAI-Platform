-- MuseAI 平台库 0051：模型**备用路由**的成本可查性（一列，不加表）。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 落地的是 docs/build/open-decisions.md §4 的第三条决定
-- ═══════════════════════════════════════════════════════════════════════════
-- 那一节把「备用路由」拆成三件必须先定的事：**形状** / **回退触发条件** / **成本口径**。
-- 前两件在代码里（`runtime::fallback`：单个 fallback profile；只在传输层失败时回退，
-- 内容错误绝不回退——那会给「模型持续输出坏 JSON」装一个成本放大器）。
-- 第三件就是这一列。
--
-- 🔴 **成本相加，不是只记成功那次**。回退意味着同一拍出现两次调用，
-- 只记成功那次会**系统性低报**，而低报的成本看板比没有成本看板更危险
-- （它会让人以为已经在看着了）。`world_ticks.cost_tokens` 的口径不变——
-- 它本来就是 `TokenMeter` 汇总引擎每一次 ModelCall 的 input+output，回退那次自然在内。
--
-- 光相加还不够：账单变贵时**没人分得清是「模型涨价了」还是「一直在回退」**。
-- 故本列如实记下这一拍走了几次备用路由。
--
-- ⚠️ 用**计数**而不是布尔：一拍里有多个环节（decide / arbiter / writer / critic / director），
-- 「五个环节全走了备用」与「只有一个环节抖了一下」是两种完全不同的健康状况，
-- 压成 0/1 就分不出来了。
--
-- 🔴 运营面的「路由错误率」必须用**本列**算，不得拿 tick 失败率顶替：
-- 回退成功的拍**不算失败**（内容照样出得来），但它正是「路由在出问题」的证据——
-- 用失败率去看，恰好把它整个漏掉。这正是设计文档 §9.1 里那一栏长期为 `—` 的原因：
-- 不是没地方显示，是没有一个**只反映路由**的数。
--
-- 双库可移植（db.rs 约定）：`ALTER TABLE ... ADD COLUMN <常量默认值>`，SQLite 与 Postgres
-- 语义一致（PG 11+ 不重写表）。存量行默认 0 —— 那是**真的**：本列上线前没有回退这回事。
-- 不加索引：读取面按 world_id 聚合，`world_ticks` 已有 (world_id, tick_no) 唯一键覆盖。

ALTER TABLE world_ticks ADD COLUMN fallback_used BIGINT NOT NULL DEFAULT 0;
