-- MuseAI 平台库 0050：if 线推进**改为异步**所需的三列（不加表）。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 补的是哪个缺口
-- ═══════════════════════════════════════════════════════════════════════════
-- `ifline::advance_ifline` 的文档注释与 `docs/VALIDATION.md` §3.2 的遗留栏都挂着同一条：
--
--   ⚠️ 本端点在请求内**同步调用模型**，长回合会是一个长连接请求。
--      生产化应改为「入队 + 后台 worker + 轮询/推送」（`queue` 模块已具备该能力）。
--
-- 它是真的生产阻塞项：一次引擎回合几十秒起步，而这中间占着一个 HTTP 连接——
-- 反向代理超时、客户端重试、移动网络切换，每一样都会把「已经烧掉的 token」变成
-- 「玩家看到失败」。而 if 线是**付费**内容（一张副本卡换一条线），这种失配最不该出现在这里。
--
-- ⚠️ 原本记着「本批次不做」的理由是「加一条独立 worker 循环会显著放大改动面且需单独评审」。
-- 那条理由现在不成立了：同一套形态（独立 topic + 独立 worker 池 + 池大小即成本闸）
-- 在 §15 第 3 层（`safety::semantic`）与它的补偿轮询（`safety::semantic::sweep`）上
-- 已经跑了两遍，改动面是已知的。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 异步化本身会引入两个新的失败形态，这三列就是为它们准备的
-- ═══════════════════════════════════════════════════════════════════════════
-- 同步版本里，「为什么没推进」是**当场返回给玩家的那句话**（原世界模型路由没配、
-- 主角卡不可读、没有可上场的 NPC……）。改成异步之后，端点先回 202，那些原因发生在 worker 里，
-- 若不落库就**彻底消失**——玩家点一下、什么都没发生、也没有任何解释。
-- 这正是本仓库反复在防的那类「静默失败」，所以异步化必须连同「把原因留下来」一起做。
--
--   last_error / last_error_at ── 上一次推进失败的原因与时刻（成功时清空）。
--
-- 第二个形态是**重复点击**。同步版本天然串行（请求还没回来，第二次点击撞的是
-- `(ifline_id, beat_no)` 唯一键 → 409）。异步版本里第二次点击会在第一份任务还没被 worker
-- 取走时就入队，于是排两份、烧两遍。故在**请求这一层**再加一道闸：
--
--   advance_requested_at ── 「已请求推进、尚未落定」的时刻（0 = 没有在飞的请求）。
--
-- 端点用 CAS 抢它（`WHERE advance_requested_at = 0 OR ... < 陈旧线`），抢不到即 409。
-- 它与 `(ifline_id, beat_no)` 唯一键是**两层不同的闸**：前者挡「同一个人连点」，
-- 后者挡「任务真的被投了两次」。少了后者不安全，少了前者要白烧一次调用。
--
-- 🔴 **陈旧线不可省**，否则这一列会造出一个比原问题更糟的死锁：`queue::MemQueue` 是
-- 进程内内存队列、**不持久**（同 §15 第 3 层那条已登记的边界）。进程重启时在飞的任务会丢，
-- 而 `advance_requested_at` 已经写下——若 CAS 只认 `= 0`，这条付费的 if 线就**永久推不动了**，
-- 且玩家已经烧掉了副本卡。故 CAS 恒带「或者它已经陈旧到不可能还有人在跑」这一支，
-- 陈旧线由 `MUSE_IFLINE_ADVANCE_STALE_MS` 参数化（§0.2），默认远大于一次回合的耗时。
--
-- ⚠️ 这不等于「丢了的任务会被自动补上」——陈旧线只是**让玩家能再点一次**。
-- 真正的补偿（对账式重投）是 §15 第 3 层 `sweep` 那种形态，if 线尚未做，如实记在
-- `docs/VALIDATION.md` 的遗留栏里。
--
-- 双库可移植（db.rs 约定）：三条 `ALTER TABLE ... ADD COLUMN <常量默认值>`，
-- SQLite 与 Postgres 语义一致（PG 11+ 不重写表）。BIGINT 毫秒 + TEXT，无方言特性。
-- 不加索引：三列都只按主键 `id` 读写（端点与 worker 都拿着 ifline_id）。

-- 「已请求推进、尚未落定」的时刻；0 = 当前没有在飞的推进请求。
ALTER TABLE ifline_worlds ADD COLUMN advance_requested_at BIGINT NOT NULL DEFAULT 0;

-- 上一次推进失败的原因（面向玩家的那句话，与同步版本当场返回的文案同源）。成功即清空。
ALTER TABLE ifline_worlds ADD COLUMN last_error TEXT NOT NULL DEFAULT '';

-- 上一次推进失败的时刻；0 = 从未失败过（或上一次已成功、被清空）。
ALTER TABLE ifline_worlds ADD COLUMN last_error_at BIGINT NOT NULL DEFAULT 0;
