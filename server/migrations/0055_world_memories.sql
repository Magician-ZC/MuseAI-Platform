-- 0055：世界记忆层——一张卡在**某一个世界**里的经历，世界结束时定格。
--
-- ════════════════════════════════════════════════════════════════════════════
-- 它和「内核」「烙印」的分工（三层，别混）
-- ════════════════════════════════════════════════════════════════════════════
-- | 层 | 谁写 | 用户可编辑 | 随卡导出 | 作用 |
-- |---|---|---|---|---|
-- | **内核**（`card_json`） | 用户捏 | ✅ | ✅ | 性格 / 执念 / 底线 / 决策模型 —— **可被复刻** |
-- | **世界记忆**（本表） | 系统按该世界确定性事实写 | ❌ | ❌ | 这张卡在那个世界里做过什么 |
-- | **烙印**（0054） | 系统按世界结局派生 | ❌ | ❌ | 跨世界的经历标签，进实例种子 |
--
-- 🔴 产品定性（2026-07-29 拍板）：**单个世界的经历不改变角色卡的内核**，
-- 只是给这张卡多加一层关于那个世界的记忆。记忆累积得足够多之后，才会影响
-- 「用户不能编辑的部分」——那一层是一张卡真正有生命的地方，也是**唯一无法被复刻的东西**：
-- 别人可以抄走你的内核，抄不走你的卡活过什么。
--
-- ════════════════════════════════════════════════════════════════════════════
-- 为什么不复用 0054 的 character_imprints
-- ════════════════════════════════════════════════════════════════════════════
-- 两者形状与用途都不同，合表会让两边都变形：
-- - 烙印是**结构化标签**（kind + code），要进实例种子做确定性哈希 ⇒ 必须短、必须可枚举；
-- - 记忆是**文本条目**（`{角色}｜{结果}｜{后果}` 的原样流水）⇒ 长、不可枚举、不进种子。
-- 合在一起，指纹计算就得开始区分"哪些条目算数"，而那正是最容易漂的一类判据。
--
-- ════════════════════════════════════════════════════════════════════════════
-- 幂等与顺序
-- ════════════════════════════════════════════════════════════════════════════
-- `(character_id, world_id, seq)` 唯一 ⇒ 结算重入变成 no-op，不需要应用层做 TOCTOU 检查。
-- `seq` 是**这张卡在这个世界里的第几条**（不是全局序），由写入方按数组下标给，
-- 因此天然连续、天然有序，不需要发号器。
--
-- 双库可移植（db.rs 约定）：id/外键 TEXT；时间 BIGINT 毫秒；无方言特性；无 CHECK 约束。

CREATE TABLE character_world_memories (
  id TEXT PRIMARY KEY,
  -- 这条记忆属于哪张卡（`cloud_characters.id`）。
  character_id TEXT NOT NULL,
  -- 在哪个世界留下的。
  world_id TEXT NOT NULL,
  -- 这张卡在**这个世界**里的第几条（从 1 起，按发生先后）。
  seq BIGINT NOT NULL,
  -- 记忆正文。来源是引擎的 `narrative.pacingNotes`，格式 `{角色id}｜{仲裁结果}｜{后果}`，
  -- 落库时**原样保留**——它是既成事实的记录，不做二次加工（加工过的记忆不可对账）。
  note TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

-- 幂等锚点：同卡同世界同序号只留一条。
CREATE UNIQUE INDEX idx_world_memories_unique
  ON character_world_memories(character_id, world_id, seq);
-- 读取面：按卡取全部记忆（生命层要数它有多少），按 (world, seq) 定序。
CREATE INDEX idx_world_memories_card
  ON character_world_memories(character_id, world_id, seq);
