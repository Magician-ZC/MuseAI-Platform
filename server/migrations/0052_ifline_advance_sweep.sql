-- MuseAI 平台库 0052：if 线推进的**对账式补偿**所需的一列（不加表）。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 补的是哪个缺口
-- ═══════════════════════════════════════════════════════════════════════════
-- `docs/VALIDATION.md` §3.2 的遗留栏第 1b 条（0050 落地时**新登记**的那一条）：
--
--   if 线没有对账式补偿：队列丢了任务只能靠陈旧线让玩家重点，没有像 §15 第 3 层 `sweep`
--   那样按数据重算待办。陈旧线只是**让玩家能再点一次**，不是把丢掉的那次补上。
--
-- 0050 的注释里把这两件事分了层：陈旧线是**安全底线**（保证玩家不被永久锁死），
-- 对账是**体验**（玩家没再点也能补上），故当时先做前者。现在补后者。
--
-- 判据是干净的，因为 0050 已经把出口收严了：`run_advance_job` 的**任何出口都清掉
-- `advance_requested_at`**（成功清、失败清并写 `last_error`）。于是
--
--   `advance_requested_at != 0` 且已陈旧  ⇒  这次推进确实丢了，且没有任何人会重试它
--
-- 三种成因（进程重启带走内存队列 / 读行失败早退 / 收尾写库失败）都归到这同一条判据下，
-- 都该补投。**不需要**去区分它们——区分不改变动作。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 为什么必须加这一列，而不是「查到就补投」
-- ═══════════════════════════════════════════════════════════════════════════
-- 补投会**真的调模型**（if 线是付费内容，一次回合几十秒、烧真 token）。若 worker 每次都在
-- 清标记之前就死掉（panic、OOM、被 kill），「查到就补投」会变成一个**无限烧钱的循环**，
-- 而且每一轮都看起来很正常。
--
-- §15 第 3 层的 `sweep` 不需要这一列，是因为它那边有尝试台账：补投用 `attempt = MAX+1`，
-- 于是既有的重试预算 `MUSE_SAFETY_L3_MAX_ATTEMPTS` 天然把补投也封了顶。if 线没有台账
-- （一拍一行 `ifline_beats`，失败的那次压根不落行），所以这个封顶得自己带。
--
--   advance_sweep_count ── 本次「在飞」被自动补投过几次。成功/失败落定即清零
--                          （那条尝试链已经结束，下一次点击是全新的一条）。
--
-- 到顶时**不是静默放弃**：清掉 `advance_requested_at` 并把原因写进 `last_error`，
-- 于是玩家立刻能再点（不必等陈旧线），且读取面能说出发生了什么。
-- 静默放弃会把「补偿机制」变成「一个更难查的静默失败」，那比没有补偿更糟。
--
-- 双库可移植（db.rs 约定）：一条 `ALTER TABLE ... ADD COLUMN <常量默认值>`，
-- SQLite 与 Postgres 语义一致（PG 11+ 不重写表）。BIGINT，无方言特性。
-- 不加索引：扫描面是 `advance_requested_at != 0` 的行——那是「当前在飞」的集合，
-- 天然极小（同时在推进的 if 线数量级 ≪ 表行数），全表扫的代价低于维护一条索引。

-- 本次「在飞」被自动补投过几次；0 = 从未被补投（或上一次已落定、被清零）。
ALTER TABLE ifline_worlds ADD COLUMN advance_sweep_count BIGINT NOT NULL DEFAULT 0;
