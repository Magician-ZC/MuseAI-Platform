-- MuseAI 平台库 0049：机审 provider 的**真实调用耗时**（补 `moderationLatency` 的数据源缺失）。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 补的是哪个缺口
-- ═══════════════════════════════════════════════════════════════════════════
-- `admin_api::worlds_ops` 的成本仪表（总规格 §17【拍板 16】）上一直挂着一个不下发的字段
-- `moderationLatency`，理由写成 `TODO(数据源缺失)`：
--
--   > 需要**每次机审调用的耗时**（provider 请求毫秒数），全仓无任何一处记录它。
--
-- 那句话在写下时成立，**但已经过期**：0046 的 `safety_recheck_runs.latency_ms` 记了耗时。
-- ⚠️ 只是它记的**不是同一件事**——`latency_ms` 是**一次尝试的全程**：开关解析 + 候选装载 +
-- N 次 `check_text` + 收紧 UPDATE + 记险 + 入人审队列。拿它除以调用数得到的
-- 「平均每次调用耗时」里混着数据库往返，而这个字段存在的意义正是**给 provider RTT 报警**
-- （前端按秒渲染、>3s 亮红）。用一个混了 DB 时间的数去报警 provider 慢，是 TODO 自己
-- 警告过的「假指标」的另一种形态：它不像 `audit_queue.reviewed_at`（人审周转，量级差几个数量级、
-- 一眼能看出不对）那样容易识破，反而**看起来完全合理**，只是系统性偏大。
--
-- 所以本迁移不去"凑"一个近似值，而是把真正缺的那半个字段补上：
-- **`provider_ms` = 这次尝试里，纯粹花在 `check_text` 上的毫秒数**（只累加 `check_with_timeout`
-- 两端的时钟差，超时/报错的那次也算——**失败的调用一样占用了 RTT 和配额**，把它们排除掉会让
-- 「provider 开始抖动」这件事在延迟曲线上反而变好看，那是最坏的一种失真）。
--
-- 于是同一行台账上有了两个可对照的数：
--
--   provider_ms                    ← provider 侧耗时（报警看这个）
--   latency_ms - provider_ms       ← 本层自己的 DB 与记账开销（调优看这个）
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 补了数据源，仍然**不下发** `worlds_ops` 的那个字段
-- ═══════════════════════════════════════════════════════════════════════════
-- 三条理由，缺一条这个字段就该发：
-- ① 当前 provider 是 Dev 桩（一张关键词表，本地匹配），耗时恒为 ~0。一个恒 0 的「审核延迟」
--    在运营看板上长得和「审核非常快」一模一样，而真相是「一次真实审核都没发生过」。
-- ② 第 3 层默认关闭（`MUSE_SAFETY_SEMANTIC_RECHECK`），大多数世界一行台账都不会有。
--    按世界聚合会得到一片 null，与「这个世界审核很快」在前端渲染上难以区分。
-- ③ 本列只覆盖**运行时投影**这条链。静态内容审核（角色卡 / 世界模板 / 装配钩子 / 入站托梦信，
--    走 `safety::moderate_and_queue`）不落这张表，也不挂在某个世界上。把只覆盖一条链的数
--    摆在世界列表里，读者会当成那个世界的机审总体 SLA。
--
-- 因此本批次把数**采准**（延迟数据不可回填——真实 provider 接上之后才开始记，第一段就永远丢了），
-- 但只在 `GET /api/admin/safety/recheck` 这个**自带 `honesty[]` 诚实边界的端点**上露出来，
-- 那里的每个数字旁边都写着「当前是桩」。`worlds_ops` 的 TODO 相应改写：不再说"无数据源"，
-- 而是说清"数据源已有，为什么仍不下发，以及下发的前提是什么"。
--
-- 双库可移植（db.rs 约定）：`ALTER TABLE ... ADD COLUMN <常量默认值>` 在 SQLite 与 Postgres 上
-- 语义一致（PG 11+ 不重写表）。BIGINT 毫秒，不用任何时间函数方言。
-- 不加索引：读取面是既有的时间窗聚合，`idx_safety_recheck_runs_created(created_at, id)` 已覆盖。

ALTER TABLE safety_recheck_runs ADD COLUMN provider_ms BIGINT NOT NULL DEFAULT 0;
