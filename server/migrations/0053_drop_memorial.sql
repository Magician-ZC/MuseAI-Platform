-- 0053：删除传世卡 · 遗作馆（memorial）的全部存储。
--
-- ════════════════════════════════════════════════════════════════════════════
-- 🔴 为什么是删，不是关
-- ════════════════════════════════════════════════════════════════════════════
-- memorial 的全部语义建立在「死亡 = 封卷 = 这张卡不可再入任何世界」之上
-- （0034 的 `memorial_status` + `withdrawn=1` 双写）。
--
-- 2026-07-29 产品模型改为：**角色卡永不损失**。「死亡」只是这张卡在**那一个副本**里的
-- 剧本结束，退场即可进下一个世界。在这条模型下，一个把卡永久锁死的机制
-- **不是「暂时关着的功能」，是错的行为**——留着它，只要有人把 `MUSE_MEMORIAL` 打开，
-- 结算就会开始永久锁卡。按本仓纪律（「关掉一条就删一条，不要打勾留着」），删干净。
--
-- ⚠️ 迁移是 append-only 的历史，0034 一个字都不改；这里加一条新迁移撤销它的结构。
--
-- ════════════════════════════════════════════════════════════════════════════
-- 双库可移植性：为什么只 DROP TABLE / INDEX，不 DROP COLUMN
-- ════════════════════════════════════════════════════════════════════════════
-- 🔴 `ALTER TABLE ... DROP COLUMN` **不在本仓的可移植子集内**：
-- SQLite 直到 3.35 才支持，且对被索引/被约束引用的列直接报错；两库的失败方式也不一致。
-- 而 `cloud_characters` 是核心表，一次失败的迁移会让整个服务起不来。
--
-- 故三列 `memorial_status` / `memorial_sealed_at` / `memorial_world_id` **保留在表上但不再有任何读写方**
-- （全仓生产代码对它们的引用已在同批提交里清零）。它们从此是**惰性残留列**：
-- 有默认值、不参与任何判定、不进任何投影。
--
-- 🔵 这是一次**有意的取舍**，写在这里免得下一个人以为是漏删：
-- 「三个不再被读的列」的代价，远小于「一条可能在生产库上失败的 DDL」。
-- 真要清列，应当在一次有停机窗口的表重建里做，而不是塞进启动自动执行的迁移链。

-- 索引先于表删（部分数据库对被索引表的 DROP 顺序敏感）。
DROP INDEX IF EXISTS idx_memorial_marks_owner;
DROP INDEX IF EXISTS idx_memorial_marks_deceased;
DROP INDEX IF EXISTS idx_cloud_characters_memorial;

-- 「故人」印记：memorial 独有的存储，无其他读写方，直接删。
DROP TABLE IF EXISTS memorial_marks;
